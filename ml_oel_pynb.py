"""4: Data Cleaning & Preprocessing"""

# ─────────────────────────────────────────────────────────────────
# SECTION 4: DATA CLEANING & PREPROCESSING
# ─────────────────────────────────────────────────────────────────

# 4.1 Fix TotalCharges — convert text to numeric
df['TotalCharges'] = pd.to_numeric(df['TotalCharges'], errors='coerce')
# pd.to_numeric() converts values to numbers
# errors='coerce' replaces unconvertible values (blank spaces) with NaN
# this turns our 11 blank spaces into proper NaN missing values
print("TotalCharges converted. NaN count:", df['TotalCharges'].isnull().sum())

# 4.2 Fill Missing Values with Median
df['TotalCharges'].fillna(df['TotalCharges'].median(), inplace=True)
# fillna() replaces NaN with a specified value
# we use MEDIAN not MEAN because median is not affected by outliers
# inplace=True modifies the original df directly
print("Missing values filled. Remaining NaN:", df['TotalCharges'].isnull().sum())

# 4.3 Remove customerID Column
df.drop('customerID', axis=1, inplace=True)
# customerID is just a unique identifier — no predictive value
# every customer has a different ID so it teaches the model nothing
# axis=1 means we are dropping a column (not a row)
print(" customerID removed. New shape:", df.shape)

# 4.4 Label Encode All Categorical Columns
le = LabelEncoder()
# create LabelEncoder object

for col in df.columns:
    if df[col].dtype == 'object':
        # dtype == 'object' means column contains text
        df[col] = le.fit_transform(df[col])
        # fit: learns unique categories in this column
        # transform: converts each category to a number
        # example: Gender → Male=1, Female=0
        # example: Churn → Yes=1, No=0
        # example: Contract → Month-to-month=0, One year=1, Two year=2

print("Label Encoding complete.")
df.dtypes
# verify all columns are now numeric

# 4.5 Separate Features and Target Variable
X = df.drop('Churn', axis=1)
# X = all columns except Churn
# these are the INPUT features we give the model

