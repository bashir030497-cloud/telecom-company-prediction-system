def predict_single_customer(customer_data):
    """
    Input  : dictionary of one customer details
    Output : churn prediction printed to screen
    """

    # convert dictionary to dataframe
    customer_df = pd.DataFrame([customer_data])
    # wrap in [] so pandas treats it as one row

    # reorder columns to match training data
    customer_df = customer_df[X.columns]
    # X.columns = the exact column order used during training
    # wrong order = wrong prediction

    # scale using the same scaler from training
    customer_scaled = scaler.transform(customer_df)
    # transform only — NOT fit_transform
    # fit_transform would recalculate scale = wrong results

    # predict
    prediction  = results[best_model]['model'].predict(customer_scaled)[0]
    probability = results[best_model]['model'].predict_proba(customer_scaled)[0]
    # [0] gets single value from array
    # probability[0] = chance of staying
    # probability[1] = chance of churning

    # display result
    print("\n" + "=" * 50)
    print("     CHURN PREDICTION RESULT")
    print("=" * 50)
    print(f"   Model used        : {best_model}")
    print(f"   Stay probability  : {round(probability[0]*100, 1)}%")
    print(f"   Churn probability : {round(probability[1]*100, 1)}%")
    print("-" * 50)

    if prediction == 1:
        print(f"   Result  : ⚠️  THIS CUSTOMER WILL CHURN")
        print(f"   Action  : Contact immediately!")
        print(f"   Suggest : Offer discount or better plan")
    else:
        print(f"   Result  : ✅  THIS CUSTOMER WILL STAY")
        print(f"   Action  : No action needed")
        print(f"   Suggest : Customer is loyal")

    print("=" * 50)
    return prediction


