# 8.1 Elbow Method — Find Optimal K
inertia = []
# stores total distance of points from their cluster center
# lower inertia = tighter better clusters

K_range = range(1, 11)
# test K values from 1 to 10

for k in K_range:
    km = KMeans(n_clusters=k, random_state=42, n_init=10)
    # n_clusters=k number of groups to form
    # n_init=10 runs KMeans 10 times, keeps best result
    km.fit(X_scaled)
    inertia.append(km.inertia_)
    # km.inertia_ = total within-cluster sum of squares

plt.figure(figsize=(8, 4))
plt.plot(K_range, inertia, marker='o', color='#3498db', linewidth=2)
# plot K on x-axis, inertia on y-axis
# look for the ELBOW POINT where curve bends sharply
plt.title('Elbow Method — Finding Optimal K', fontsize=14, fontweight='bold')
plt.xlabel('Number of Clusters (K)', fontsize=12)
plt.ylabel('Inertia', fontsize=12)
plt.xticks(K_range)
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()
