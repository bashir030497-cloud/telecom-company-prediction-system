# 8.7 DBSCAN Clustering
dbscan = DBSCAN(eps=1.5, min_samples=10)
# eps=1.5 maximum distance between two points to be neighbors
# min_samples=10 minimum points needed to form a dense region
# points with fewer than 10 neighbors = labeled as NOISE (-1)

dbscan_labels = dbscan.fit_predict(X_scaled)
# labels: 0,1,2... = cluster numbers
# -1 = NOISE (outlier customer that fits no cluster)

n_clusters = len(set(dbscan_labels)) - (1 if -1 in dbscan_labels else 0)
# count unique labels, subtract 1 if noise label -1 is present
