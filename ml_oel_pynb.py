def predict_batch(csv_path):
    """
    Input  : path to CSV file with new customers
    Output : results table + saved CSV file
    """

    # load new customer data
    new_df = pd.read_csv(csv_path)

    # store and remove customerID if present
    if 'customerID' in new_df.columns:
        customer_ids = new_df['customerID']
        new_df.drop('customerID', axis=1, inplace=True)
    else:
        customer_ids = ['CUST_' + str(i) for i in range(1, len(new_df)+1)]
        # auto generate IDs if not present

    # remove Churn column if present
    if 'Churn' in new_df.columns:
        new_df.drop('Churn', axis=1, inplace=True)

    # reorder columns to match training
    new_df = new_df[X.columns]

    # scale data
    new_scaled = scaler.transform(new_df)

    # predict all customers
    predictions   = results[best_model]['model'].predict(new_scaled)
    probabilities = results[best_model]['model'].predict_proba(new_scaled)[:, 1]
    # [:,1] = churn probability for every customer

    # build results table
    results_table = pd.DataFrame({
        'CustomerID'         : customer_ids,
        'Churn_Prediction'   : ['CHURN ⚠️' if p==1 else 'STAY ✅' for p in predictions],
        'Churn_Probability %': [round(p*100, 1) for p in probabilities],
        'Action'             : ['Contact Now 🔴' if p==1 else 'No Action 🟢' for p in predictions]
    })

    # sort by highest churn risk first
    results_table = results_table.sort_values(
        'Churn_Probability %',
        ascending=False
    ).reset_index(drop=True)

    # print results
    print("=" * 65)
    print("   BATCH CHURN PREDICTION RESULTS")
    print("=" * 65)
    print(results_table.to_string(index=False))
    print("=" * 65)
    print(f"   Total customers : {len(results_table)}")
    print(f"   Will churn      : {sum(predictions)}")
    print(f"   Will stay       : {len(predictions) - sum(predictions)}")
    print(f"   Churn rate      : {round(sum(predictions)/len(predictions)*100,1)}%")
    print("=" * 65)

    # save results to CSV
    results_table.to_csv('churn_predictions.csv', index=False)
    print(f"\n Results saved to churn_predictions.csv")

    return results_table


